_LANGUAGE_ALIASES = {
    "en": "en",
    "english": "en",
    "ja": "ja",
    "japanese": "ja",
}


def normalize_language(language: str | None) -> str:
    """Map a saved or user-supplied language value to a supported UI language."""
    return _LANGUAGE_ALIASES.get(str(language or "").strip().lower(), "zh")


def set_language(language: str):
    global current_language
    current_language = normalize_language(language)


def tr(key: str, **kwargs) -> str:
    entry = _STRINGS.get(key)
    if entry is None:
        return key
    text = entry.get(current_language) or entry["zh"]
    if kwargs:
        text = text.format(**kwargs)
    return text
